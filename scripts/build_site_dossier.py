#!/usr/bin/env python3
"""Write src/marking/site_116.py: the 116 縣道 numbers the endpoint attaches.

The endpoint image copies src/ only (aws/Dockerfile), so the site's
published figures are frozen into a module here. Every value is read
from results/ and carries the file and key it came from;
tests/test_site_dossier.py re-reads results/ and fails if they drift.

None of this is measured from the caller's photograph. The endpoint
attaches it to every response, by the owner's decision (2026-09-23), under
a key that says so.

    /opt/anaconda3/bin/python3 -B scripts/build_site_dossier.py
"""
import json
import pprint
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(name):
    return json.loads((ROOT / "results" / name).read_text())


def build():
    # 2026-10-13: only figures measured on the owner's own photographs. The along-road
    # distances, grate positions and merge times came from Google Street View, whose terms
    # do not allow sharing derived data; the 9.2-11.9 taper was withdrawn. All removed.
    gaps = {f: load(f"redline_gap_{f}.json")["summary"] for f in ("F30", "F31", "F32")}
    gc = load("grate_crossings_2026-09-23.json")
    crossing = [r for r in gc if r.get("red_axis_crosses_grate")]
    dist = [r["red_axis_to_grate_centre_cm"] for r in crossing]
    dr = load("dash_ruler_P64.json")
    return {
        "site": "116 縣道 樹林中正路,雙白實線起點(「往板橋/往樹林」標字)往橋頭",
        "measured_from_this_photograph": False,
        "items": [
            {"what": "紅線外移(新紅線內緣到舊紅線中心)",
             "value_m": {f: g["median_m"] for f, g in gaps.items()},
             "source": "results/redline_gap_F30.json, _F31.json, _F32.json#/summary/median_m"},
            {"what": "俯拍照片中新紅線中軸穿過格柵溝蓋",
             "value_count": {"crossing": len(crossing), "top_down_photos": len(gc),
                             "grates": sorted({r["group"] for r in crossing})},
             "value_cm": {"min": min(dist), "max": max(dist)},
             "source": "results/grate_crossings_2026-09-23.json"},
            {"what": "槽化線島遠端斜邊與路軸夾角(車道虛線 4 m + 6 m 為尺)",
             "value_deg": dr["slanted_end_edge"]["angle_deg"],
             "range_deg": [dr["monte_carlo"]["angle_deg"]["p10"], dr["monte_carlo"]["angle_deg"]["p90"]],
             "source": "results/dash_ruler_P64.json#/slanted_end_edge"},
        ],
    }


def main():
    d = build()
    text = ('"""Generated by scripts/build_site_dossier.py from results/. Do not edit.\n\n'
            'tests/test_site_dossier.py fails if this drifts from results/.\n"""\n\n'
            "SITE_116 = " + pprint.pformat(d, width=100, sort_dicts=False) + "\n")
    (ROOT / "src" / "marking" / "site_116.py").write_text(text)
    print("寫入 src/marking/site_116.py")


if __name__ == "__main__":
    main()
